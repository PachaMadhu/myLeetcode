class Solution {
    public long countCommas(long n) {
        long x=n;
        int a=0;
        while(x>0){
            // int dig=x%10;
            a++;
            x/=10;
        }

        int q=(a-1)/3;

        if(q==0){
            return 0;
        }else if(q==1){
            return n-999;
        }else if(q==2){
            return (999999L - 999) + 2 * (n - 999999L);
        } else if (q == 3) {
            return (999999 - 999)
                    + 2 * (999999999 - 999999)
                    + 3 * (n - 999999999);
        } else if (q == 4) {
            return (999999 - 999)
                    + 2 * (999999999 - 999999)
                    + 3 * (999999999999L - 999999999)
                    + 4 * (n - 999999999999L);
        } else if (q == 5) {
            return (999999 - 999)
                    + 2 * (999999999 - 999999)
                    + 3 * (999999999999L - 999999999)
                    + 4 * (999999999999999L - 999999999999L)
                    + 5 * (n - 999999999999999L);
        }
        return 0;
    }
}

